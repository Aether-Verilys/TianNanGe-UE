import unreal as u
assets=u.get_editor_subsystem(u.EditorAssetSubsystem)
mat=assets.load_asset('/Game/TianNanGe/Materials/M_006')
nodes=u.MaterialEditingLibrary.get_material_expressions(mat)
inverse=next(n for n in nodes if isinstance(n,u.MaterialExpressionOneMinus))
mask=next(n for n in nodes if isinstance(n,u.MaterialExpressionTextureSample) and 'MaskMap' in n.texture.get_name())
assert u.MaterialEditingLibrary.connect_material_expressions(mask,'A',inverse,'')
u.MaterialEditingLibrary.recompile_material(mat);assets.save_loaded_asset(mat)
mat=assets.load_asset('/Game/TianNanGe/Lighting/M_Kloofendal_Sky')
nodes=u.MaterialEditingLibrary.get_material_expressions(mat)
rotate=next(n for n in nodes if isinstance(n,u.MaterialExpressionCustom))
cube=next(n for n in nodes if isinstance(n,u.MaterialExpressionTextureSampleParameterCube))
assert u.MaterialEditingLibrary.connect_material_expressions(rotate,'',cube,'UVs')
u.MaterialEditingLibrary.recompile_material(mat);assets.save_loaded_asset(mat)
u.log('TIANNANGE_MATERIAL_PINS_OK')
