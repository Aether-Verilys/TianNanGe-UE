"""Render three seconds of the real Niagara simulation from the reference camera."""
import unreal as u,json,time
from pathlib import Path
root=Path(__file__).resolve().parents[1];assets=u.get_editor_subsystem(u.EditorAssetSubsystem)
command=globals().get('COMMAND',{});frame_count=command.get('frames',72)
width=command.get('width',1280);height=command.get('height',620);tag=command.get('tag','EasySnowMotion')
actors=u.get_editor_subsystem(u.EditorActorSubsystem).get_all_level_actors()
camera=next(a for a in actors if isinstance(a,u.CameraActor) and a.get_actor_label().startswith('Main Camera'))
sequence_name='LS_'+tag
sequence_path='/Game/TianNanGe/EasySnowIntegration/Preview/'+sequence_name
seq=assets.load_asset(sequence_path) if assets.does_asset_exist(sequence_path) else u.AssetToolsHelpers.get_asset_tools().create_asset(sequence_name,'/Game/TianNanGe/EasySnowIntegration/Preview',u.LevelSequence,u.LevelSequenceFactoryNew())
seq.set_display_rate(u.FrameRate(24,1));seq.set_playback_start(0);seq.set_playback_end(frame_count)
for track in seq.get_tracks():seq.remove_track(track)
for binding in seq.get_bindings():binding.remove()
binding=seq.add_possessable(camera)
track=seq.add_track(u.MovieSceneCameraCutTrack);section=track.add_section();section.set_range(0,frame_count)
binding_id=u.MovieSceneObjectBindingID();binding_id.set_editor_property('guid',binding.get_id())
section.set_camera_binding_id(binding_id)
assets.save_loaded_asset(seq)
capture=u.AutomatedLevelSequenceCapture()
capture.set_editor_property('level_sequence_asset',u.SoftObjectPath(sequence_path))
capture.set_editor_property('use_separate_process',False)
capture.set_editor_property('use_custom_start_frame',True);capture.set_editor_property('custom_start_frame',u.FrameNumber(0))
capture.set_editor_property('use_custom_end_frame',True);capture.set_editor_property('custom_end_frame',u.FrameNumber(frame_count))
capture.set_editor_property('warm_up_frame_count',144);capture.set_editor_property('delay_before_warm_up',2.)
capture.set_editor_property('write_edit_decision_list',False);capture.set_editor_property('write_final_cut_pro_xml',False)
settings=capture.get_editor_property('settings')
settings.set_editor_property('resolution',u.CaptureResolution(width,height))
settings.set_editor_property('use_custom_frame_rate',True)
settings.set_editor_property('custom_frame_rate',u.FrameRate(24,1))
settings.set_editor_property('output_directory',u.DirectoryPath(str(root/'Captures'/tag)))
settings.set_editor_property('output_format','EasySnow_{frame}')
settings.set_editor_property('overwrite_existing',True)
settings.set_editor_property('enable_texture_streaming',False)
capture.set_editor_property('settings',settings)
capture.set_image_capture_protocol_type(u.ImageSequenceProtocol_PNG)
capture.set_audio_capture_protocol_type(u.NullAudioCaptureProtocol)
def on_finished(success):
    (root/('Saved/EasySnow/'+tag+'-capture.json')).write_text(json.dumps({'success':success,'time':time.time(),'frames':frame_count,'fps':24,'resolution':[width,height],'sequence':sequence_path,'output':str(root/'Captures'/tag)},indent=2))
    u.get_editor_subsystem(u.LevelEditorSubsystem).pilot_level_actor(camera)
finished=u.OnRenderMovieStopped();finished.bind_callable(on_finished)
assert u.SequencerTools.render_movie(capture,finished)
